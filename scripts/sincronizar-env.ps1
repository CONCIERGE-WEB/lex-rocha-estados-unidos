    "GOOGLE_OAUTH_CLIENT_SECRET",
    "RESEND_API_KEY",
    "RESEND_FROM_EMAIL",
    "FOCUS_NFE_AUTO"
)
$siteLines = @("# Generated by sincronizar-env.ps1", "")
foreach ($k in $siteKeys) {
    if ($vars.ContainsKey($k)) { $siteLines += "$k=$($vars[$k])" }
}
$siteLines | Set-Content (Join-Path $root "site\.env.local") -Encoding UTF8
Write-Host "OK: site\.env.local"

