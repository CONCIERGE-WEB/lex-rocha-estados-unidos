# Sync credentials from .env.local (root) to site/.env.local and signalhub/usa/.env
$ErrorActionPreference = "Stop"
$root = Split-Path $PSScriptRoot -Parent
$master = Join-Path $root ".env.local"

if (-not (Test-Path $master)) {
    Write-Host "Missing .env.local at root. Copy .env.local.example to .env.local"
    exit 1
}

$vars = @{}
Get-Content $master -Encoding UTF8 | ForEach-Object {
    $line = $_.Trim()
    if (-not $line -or $line.StartsWith("#")) { return }
    if ($line -match '^([^=]+)=(.*)$') {
        $vars[$Matches[1].Trim()] = $Matches[2].Trim()
    }
}

